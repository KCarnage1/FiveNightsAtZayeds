#!/usr/bin/env bash
# Builds the Rust animatronic brain (rust/fnaz-ai) to WebAssembly and writes fnaz-ai.wasm.js, which the game loads.
# The module is embedded as base64 in a script so it works the same from a web server, the phone app and the desktop app (file://).
# Needs: rustup target add wasm32-unknown-unknown
set -euo pipefail
cd "$(dirname "$0")/../rust/fnaz-ai"
cargo build --release --target wasm32-unknown-unknown
WASM=target/wasm32-unknown-unknown/release/fnaz_ai.wasm
OUT=../../fnaz-ai.wasm.js
{ printf '/* Generated by scripts/build-wasm.sh from rust/fnaz-ai. Do not edit. */\nwindow.FNAZ_AI_WASM="'; base64 -w0 "$WASM"; printf '";\n'; } > "$OUT"
echo "wrote $(basename "$OUT"): $(wc -c < "$WASM") byte module"
